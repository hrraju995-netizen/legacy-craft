export function getAllBlogPosts() {
  return BLOG_POSTS;
}

export function getBlogPostBySlug(slug) {
  if (!slug) return null;
  const normalized = decodeURIComponent(slug).toLowerCase().trim();
  return (
    BLOG_POSTS.find(
      (p) => p.slug.toLowerCase() === normalized || String(p.id) === normalized
    ) || null
  );
}

export function getRelatedBlogPosts(currentSlug, limit = 3) {
  const current = getBlogPostBySlug(currentSlug);
  return BLOG_POSTS.filter((p) => p.slug !== current?.slug).slice(0, limit);
}

export function getBlogCategories() {
  const set = new Set(BLOG_POSTS.map((p) => p.category));
  return Array.from(set);
}
